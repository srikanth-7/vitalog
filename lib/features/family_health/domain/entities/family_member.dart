class FamilyMember {
  const FamilyMember({
    required this.id,
    required this.name,
    required this.relation,
    required this.initials,
    required this.colorValue,
    required this.age,
  });

  final String id;
  final String name;
  final String relation;
  final String initials;
  final int colorValue;
  final int age;
}
